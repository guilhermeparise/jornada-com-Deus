create table if not exists fixed_messages (
  id bigint generated by default as identity primary key,
  content text not null,
  category text default 'devotional', -- 'devotional', 'strong', 'motivational'
  active boolean default true,
  created_at timestamp with time zone default timezone('utc'::text, now())
);

alter table fixed_messages enable row level security;

create policy "Public can view active messages" on fixed_messages for select using (active = true);